#!/usr/bin/env python3
"""Derive Fern overrides from the published paywise OpenAPI specs.

The specs in ``openapi/`` are copied verbatim from the Knowledge Center
(paywise-gmbh/docs, ``api-docs/<api>/openapi.json``) and stay vendor-neutral.
Everything Fern-specific lives in ``fern/overrides/<api>.yml``, which this
script regenerates, so a spec refresh never needs hand edits:

* ``x-fern-server-name`` on each server, so the SDKs expose Production and
  Sandbox environments instead of a single default URL.
* ``x-fern-pagination`` on every list operation whose 200 response carries
  ``next`` + ``results``. All paywise lists (cursor, offset and the event
  feed's ``since`` cursor) return ``next`` as a full URL, so ``next_uri``
  covers every variant with one rule.

Usage: python3 scripts/build_fern_overrides.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APIS = ("case-management", "partner")
SERVER_NAMES = {
    "https://api.paywise.de": "Production",
    "https://api-sandbox.paywise.de": "Sandbox",
}
HEADER = (
    "# Generated by scripts/build_fern_overrides.py from openapi/{api}-api.json.\n"
    "# Do not edit by hand; rerun the script after refreshing the spec.\n"
)


def resolve(schema: dict, components: dict) -> dict:
    while "$ref" in schema:
        schema = components[schema["$ref"].rsplit("/", 1)[-1]]
    return schema


def build(api: str) -> dict:
    spec = json.loads((ROOT / "openapi" / f"{api}-api.json").read_text())
    components = spec.get("components", {}).get("schemas", {})

    servers = []
    for server in spec.get("servers", []):
        name = SERVER_NAMES.get(server["url"])
        if name is None:
            sys.exit(f"{api}: unknown server {server['url']!r}; add it to SERVER_NAMES")
        servers.append({**server, "x-fern-server-name": name})

    paths: dict = {}
    for path, operations in spec["paths"].items():
        get = operations.get("get")
        if not get:
            continue
        content = get.get("responses", {}).get("200", {}).get("content", {})
        schema = content.get("application/json", {}).get("schema")
        if not schema:
            continue
        properties = resolve(schema, components).get("properties", {})
        if {"next", "results"} <= properties.keys():
            paths[path] = {
                "get": {
                    "x-fern-pagination": {
                        "next_uri": "$response.next",
                        "results": "$response.results",
                    }
                }
            }

    return {"servers": servers, "paths": paths}


def main() -> None:
    for api in APIS:
        overrides = build(api)
        target = ROOT / "fern" / "overrides" / f"{api}.yml"
        # JSON is valid YAML; keeps the script dependency-free.
        target.write_text(HEADER.format(api=api) + json.dumps(overrides, indent=2) + "\n")
        print(f"{api}: {len(overrides['servers'])} servers, {len(overrides['paths'])} paginated lists -> {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
